/// The seven sounds shared with web (guide §2). Files `pp-<name>.wav`, generated by the web repo's
/// `scripts/feedback-sounds/make_feedback_sounds.py` (masters copied to `docs/design/feedback/sounds/`).
nonisolated enum FeedbackSound: String, CaseIterable, Equatable {
    case success
    case sent
    case approved
    case resolved
    case removed
    case error
    case queued

    /// The bundled file name without extension (`Resources/Sounds/pp-<name>.wav`).
    var fileName: String { "pp-\(rawValue)" }
    static let fileExtension = "wav"
}

/// The outcome haptics (guide §3), played through `HSHaptic`.
nonisolated enum FeedbackHaptic: String, CaseIterable, Equatable {
    case success
    case sent
    case removed
    case error
    case warn
}

