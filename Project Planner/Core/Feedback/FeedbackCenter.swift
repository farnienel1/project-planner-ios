/// Which event an outcome the app has ALREADY decided plays. Pure, so every call site's choice is tested. Each one
/// reads the app's existing decision (saved / Pending sync / refused) — never a new one.
enum FeedbackDecision {
    /// One write's own outcome (`BookingSaveResult`): saved → `success`, queued as Pending sync → `savedOffline`,
    /// refused → `actionRefused`, a double tap's second call → nothing (the save already running reports it).
    static func event(for result: BookingSaveResult, success: FeedbackEvent) -> FeedbackEvent? {
        switch result {
        case .saved: return success
        case .queued: return .savedOffline
        case .refused: return .actionRefused
        case .alreadySaving: return nil
        }
    }

    /// A bulk save's outcome (`ScheduleBookingSaveOutcome.decide`): one sound for the whole action. A partly saved
    /// action plays the error feedback (owner decision 3); "Nothing to save" plays nothing (owner decision 4).
    static func event(for outcome: ScheduleBookingSaveOutcome, success: FeedbackEvent) -> FeedbackEvent? {
        switch outcome {
        case .confirmed: return success
        case .pendingSync: return .savedOffline
        case .savedWithProblem, .notSaved: return .actionRefused
        case .nothingToSave: return nil
        }
    }

    /// Several writes of one action, decided as Schedule booking decides them.
    static func event(forResults results: [BookingSaveResult], success: FeedbackEvent) -> FeedbackEvent? {
        event(for: ScheduleBookingSaveOutcome.decide(results: results), success: success)
    }

    /// A warning dealt with by this person: `allWarningsClear` when their own Warnings list is now empty (owner
    /// decision 11), else `warningResolved`.
    static func warningResolved(remainingActiveCount: Int) -> FeedbackEvent {
        remainingActiveCount == 0 ? .allWarningsClear : .warningResolved
    }

    /// A save that reports a refusal message (nil when saved): timesheets, OT, claims, invites.
    static func event(refusal: String?, success: FeedbackEvent) -> FeedbackEvent {
        refusal == nil ? success : .actionRefused
    }

    /// A price work or expense review Approve: `claimsApproved` when the review plan (`payeClaimReviewWrites`) counts
    /// at least one approved item — an approval left unchanged is not written but still counts — else
    /// `claimsDeclined` (guide v1.1 §4).
    static func claimsReviewed(approvedCount: Int) -> FeedbackEvent {
        approvedCount > 0 ? .claimsApproved : .claimsDeclined
    }

    /// An annual leave save: Pending sync on this phone (`HolidayStore.isPendingSync`) → `savedOffline`.
    static func leaveEvent(pendingSync: Bool, success: FeedbackEvent) -> FeedbackEvent {
        pendingSync ? .savedOffline : success
    }
}

/// Plays a sound. Returns false when it could not (missing file, no audio) — never throws.
@MainActor
protocol FeedbackSoundOutput: AnyObject {
    @discardableResult func play(_ sound: FeedbackSound) -> Bool
}

/// Plays a haptic.
@MainActor
protocol FeedbackHapticOutput: AnyObject {
    func play(_ haptic: FeedbackHaptic)
    func prepare()
}

/// What `Feedback.play` talks to: the real `FeedbackCenter`, or a spy in tests.
@MainActor
protocol FeedbackPlaying: AnyObject {
    func play(_ event: FeedbackEvent)
    func prepare()
}

/// The one entry point for screens.
enum Feedback {
    /// Replaced by a spy in tests; the app never changes it.
    static var player: FeedbackPlaying = FeedbackCenter.shared

    static func play(_ event: FeedbackEvent?) {
        guard let event else { return }
        player.play(event)
    }

    static func play(_ result: BookingSaveResult, success: FeedbackEvent) {
        play(FeedbackDecision.event(for: result, success: success))
    }

    static func play(_ outcome: ScheduleBookingSaveOutcome, success: FeedbackEvent) {
        play(FeedbackDecision.event(for: outcome, success: success))
    }

    static func play(results: [BookingSaveResult], success: FeedbackEvent) {
        play(FeedbackDecision.event(forResults: results, success: success))
    }

    /// Guide §3: readies the haptic engine when a confirming button is pressed, so the haptic lands with the sound.
    static func prepare() {
        player.prepare()
    }
}

/// The real feedback service: settings, the 400 ms throttle, then the sound and the haptic.
final class FeedbackCenter: FeedbackPlaying {
    static let shared = FeedbackCenter()

    static let soundsKey = "pp.feedback.sounds"
    static let hapticsKey = "pp.feedback.haptics"
    /// Guide §1.3: at most one feedback every 400 ms.
    static let throttleInterval: TimeInterval = 0.4

    private let defaults: UserDefaults
    private let sounds: FeedbackSoundOutput
    private let haptics: FeedbackHapticOutput
    private let now: () -> Date
    private var lastPlayedAt: Date?

    init(
        defaults: UserDefaults = .standard,
        sounds: FeedbackSoundOutput? = nil,
        haptics: FeedbackHapticOutput? = nil,
        now: @escaping () -> Date = Date.init
    ) {
        self.defaults = defaults
        self.sounds = sounds ?? BundleFeedbackSoundOutput()
        self.haptics = haptics ?? HSHapticFeedbackOutput()
        self.now = now
    }

    /// Default on (owner decision 1); only an explicit false turns it off.
    static func soundsEnabled(_ defaults: UserDefaults = .standard) -> Bool {
        defaults.object(forKey: soundsKey) as? Bool ?? true
    }

    static func hapticsEnabled(_ defaults: UserDefaults = .standard) -> Bool {
        defaults.object(forKey: hapticsKey) as? Bool ?? true
    }

    func play(_ event: FeedbackEvent) {
        // The toggles first (review of #239): with nothing to play, the throttle window is not started.
        let sound = Self.soundsEnabled(defaults) ? event.sound : nil
        let playsHaptic = Self.hapticsEnabled(defaults)
        guard sound != nil || playsHaptic else { return }
        let time = now()
        if let last = lastPlayedAt, time >= last, time.timeIntervalSince(last) < Self.throttleInterval {
            return
        }
        lastPlayedAt = time
        if let sound {
            sounds.play(sound)
        }
        if playsHaptic {
            haptics.play(event.haptic)
        }
    }

    func prepare() {
        guard Self.hapticsEnabled(defaults) else { return }
        haptics.prepare()
    }

    /// Settings → "Play a sample": the success feedback, with the person's own toggles, outside the throttle.
    func playSample() {
        if Self.soundsEnabled(defaults) {
            sounds.play(.success)
        }
        if Self.hapticsEnabled(defaults) {
            haptics.play(.success)
        }
    }
}

/// Sounds from the app bundle through `AVAudioPlayer`. Nothing loads until the first sound plays.
final class BundleFeedbackSoundOutput: FeedbackSoundOutput {
    /// Owner decision 12: iOS volume 0.6.
    static let volume: Float = 0.6
    /// Guide §1.5: the silent switch mutes it and the person's music keeps playing.
    static let audioSessionCategory: AVAudioSession.Category = .ambient

    private let bundle: Bundle
    private var players: [FeedbackSound: AVAudioPlayer] = [:]
    private var unavailable: Set<FeedbackSound> = []
    private var sessionConfigured = false

    init(bundle: Bundle = .main) {
        self.bundle = bundle
    }

    /// Where a sound file is in the bundle. The synchronized `Project Planner` folder copies resources to the bundle
    /// root (as `canonical-business.js`); the subfolders are tried too.
    static func url(for sound: FeedbackSound, in bundle: Bundle) -> URL? {
        bundle.url(forResource: sound.fileName, withExtension: FeedbackSound.fileExtension)
            ?? bundle.url(forResource: sound.fileName, withExtension: FeedbackSound.fileExtension, subdirectory: "Sounds")
            ?? bundle.url(forResource: sound.fileName, withExtension: FeedbackSound.fileExtension, subdirectory: "Resources/Sounds")
    }

    /// Sets the `.ambient` category once, on the first sound. A failure is ignored (the sound may still play).
    static func configureAudioSession(_ session: AVAudioSession = .sharedInstance()) {
        do {
            try session.setCategory(audioSessionCategory)
        } catch {
            #if DEBUG
            print("Feedback: audio session not set (\(error.localizedDescription))")
            #endif
        }
    }

    @discardableResult
    func play(_ sound: FeedbackSound) -> Bool {
        guard let player = player(for: sound) else { return false }
        player.currentTime = 0
        return player.play()
    }

    private func player(for sound: FeedbackSound) -> AVAudioPlayer? {
        if let player = players[sound] { return player }
        guard !unavailable.contains(sound) else { return nil }
        if !sessionConfigured {
            sessionConfigured = true
            Self.configureAudioSession()
        }
        guard let url = Self.url(for: sound, in: bundle) else {
            unavailable.insert(sound)
            #if DEBUG
            print("Feedback: \(sound.fileName).\(FeedbackSound.fileExtension) is not in the app bundle")
            #endif
            return nil
        }
        do {
            let player = try AVAudioPlayer(contentsOf: url)
            player.volume = Self.volume
            player.prepareToPlay()
            players[sound] = player
            return player
        } catch {
            unavailable.insert(sound)
            #if DEBUG
            print("Feedback: \(sound.fileName) could not load (\(error.localizedDescription))")
            #endif
            return nil
        }
    }
}

/// Haptics through the existing `HSHaptic` helper (guide §3: no second helper).
final class HSHapticFeedbackOutput: FeedbackHapticOutput {
    func play(_ haptic: FeedbackHaptic) {
        switch haptic {
        case .success: HSHaptic.success()
        case .sent: HSHaptic.sent()
        case .removed: HSHaptic.removed()
        case .error: HSHaptic.error()
        case .warn: HSHaptic.warn()
        }
    }

    func prepare() {
        HSHaptic.prepareOutcome()
    }
}
