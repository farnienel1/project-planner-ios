//  Feedback sounds and haptics (docs/design/feedback/feedback-sounds-haptics-guide.md, v1.1, 16 Nov 2026). Not a
//  business rule and not in the rulebook (§15 "Platform-specific (not synced)"): a short sound and a tap played AFTER
//  an action this person took on this phone has succeeded, been saved to the offline queue, or been refused. It never
//  changes what the action does — saves, the offline queue, data, banners and navigation are untouched (platform
//  guardrail 7). Nothing here reads or writes Firestore; the two settings live in `UserDefaults` on this phone only.
//
//  Screens call `Feedback.play(_:)` with a named event; the event alone decides the sound and the haptic (guide §4).
//  Owner decisions 16 Nov: sounds and haptics on by default (`pp.feedback.sounds`, `pp.feedback.haptics`); volume 0.6;
//  the `.ambient` audio session (the silent switch mutes it, it never stops the person's music); players load lazily
//  on first use, never at launch; feedback plays only for the person's own action — never for listeners, sync replay,
//  other people's changes, launch or autosave.
//

